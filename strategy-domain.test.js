const assert=require('node:assert/strict');
const {migrateLegacy,duplicateScenario,assessScenario}=require('./strategy-domain.js');
const legacy={assetId:'A',name:'Test',start:'2026-11-01',value:70000000,tenancies:[{unit:'Ground',occupier:'A',area:1000,rent:100000,erv:150000},{unit:'First',occupier:'B',area:2000,rent:200000,erv:250000}],options:{hold:{name:'Hold',exitMonths:60,exitYield:6.25},active:{name:'Active',exitMonths:60,exitYield:6.25}},interventions:{active:{0:[{action:'regear',eventDate:'2027-01-01',rent:120000}]}},unitYields:{active:{0:{baseYield:6.25,reviewed:true,rationale:'Comparable evidence'}}},marketShifts:{active:0.25}};
const original=JSON.stringify(legacy);
const v2=migrateLegacy(legacy);
assert.equal(v2.schemaVersion,2);
assert.equal(v2.asset.units.length,2);
assert.equal(v2.asset.leases.length,2);
assert.equal(v2.scenarios.length,2);
assert.equal(v2.scenarios[1].unitPlans['unit-1'].actions[0].type,'regear');
assert.equal(v2.scenarios[1].exit.marketShift,0.25);
assert.equal(JSON.stringify(legacy),original,'Migration mutated source');
assert.deepEqual(migrateLegacy(v2),v2,'V2 migration should be idempotent');
const copy=duplicateScenario(v2,'active','active-2');
assert.equal(copy.scenarios.length,3);
assert.notEqual(copy.scenarios[1].unitPlans['unit-1'].actions[0].id,copy.scenarios[2].unitPlans['unit-1'].actions[0].id);
copy.scenarios[2].unitPlans['unit-1'].actions[0].parameters.rent=999999;
copy.scenarios[2].unitPlans['unit-1'].yieldAssumptions.baseYield=9;
assert.equal(copy.scenarios[1].unitPlans['unit-1'].actions[0].parameters.rent,120000);
assert.equal(copy.scenarios[1].unitPlans['unit-1'].yieldAssumptions.baseYield,6.25);
assert.equal(v2.scenarios.length,2,'Duplication mutated original');
assert.equal(assessScenario(v2,'active').status,'Provisional');
assert.throws(()=>duplicateScenario(v2,'active','hold'));
assert.throws(()=>duplicateScenario(v2,'missing','new'));
console.log('Strategy-first domain tests passed');

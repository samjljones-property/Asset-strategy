const assert=require('node:assert/strict');
const {migrateLegacy,duplicateScenario}=require('./strategy-domain.js');
const {adapt}=require('./scenario-adapter.js');
const {assetCashflow}=require('./lease-engine.js');
const demo=require('./seven-unit-demo.json');
const model=migrateLegacy(demo);
assert.equal(model.asset.units.length,7);
const first=adapt(model,'baseline');
assert.equal(first.tenancies.length,7);
assert.equal(first.engineInput.exitYield,6.25);
const result=assetCashflow(first.engineInput);
assert.equal(result.rows.length,61);
const duplicated=duplicateScenario(model,'security','test-copy','Alternative');
duplicated.scenarios.find(s=>s.id==='test-copy').unitPlans['1'].actions[0].parameters.rent=800000;
const original=adapt(duplicated,'security');
const revised=adapt(duplicated,'test-copy');
assert.equal(original.interventions[1][0].rent,735000);
assert.equal(revised.interventions[1][0].rent,800000);
assert.notEqual(assetCashflow(original.engineInput).metrics.totalRent,assetCashflow(revised.engineInput).metrics.totalRent);
